import { expect, test } from '@playwright/test'

test('new owner registers, keeps the session, adds a pet, and logs in again', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '立即注册', exact: true }).click()
  await expect(page.getByRole('heading', { name: '创建宠主账号' })).toBeVisible()
  await page.getByLabel('账号', { exact: true }).fill('registered_owner')
  await page.getByLabel('姓名', { exact: true }).fill('夏小满')
  await page.getByLabel('联系电话', { exact: true }).fill('13900939001')
  await page.getByLabel('设置密码', { exact: true }).fill('StrongPass123!')
  await page.getByLabel('确认密码', { exact: true }).fill('DifferentPass123!')
  await page.getByRole('button', { name: '注册并进入', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('两次输入的密码不一致')
  await page.getByLabel('确认密码', { exact: true }).fill('StrongPass123!')
  const registration = page.waitForResponse(response => new URL(response.url()).pathname === '/api/auth/register')
  await page.getByRole('button', { name: '注册并进入', exact: true }).click()
  expect((await registration).status()).toBe(200)
  await expect(page.getByRole('heading', { name: '夏小满，欢迎回来。' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '夏小满，欢迎回来。' })).toBeVisible()
  await page.getByRole('button', { name: '我的爱宠', exact: true }).click()
  await expect(page.getByText('当前筛选下暂无宠物档案。')).toBeVisible()
  await expect(page.getByRole('heading', { name: '糯米', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '添加爱宠', exact: true }).first().click()
  const pet = page.getByRole('dialog', { name: '添加爱宠' })
  await pet.getByLabel('宠物昵称', { exact: true }).fill('小满')
  await pet.getByRole('button', { name: '建立档案', exact: true }).click()
  await expect(page.getByRole('heading', { name: '小满', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByLabel('账号', { exact: true }).fill('registered_owner')
  await page.getByLabel('密码', { exact: true }).fill('StrongPass123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '夏小满，欢迎回来。' })).toBeVisible()
})
